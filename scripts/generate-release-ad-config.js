#!/usr/bin/env node

const fs = require('node:fs');
const path = require('node:path');

const defaultOutput = path.resolve(__dirname, '..', 'utils', 'release-ad-config.js');
const args = process.argv.slice(2);
const isDevConfig = args.includes('--dev');
const isValidation = args.includes('--validate');
const output = defaultOutput;

function fail(message) {
  process.stderr.write(`${message}\n`);
  process.exitCode = 1;
}

function isUsableRewardedVideoAdUnit(value) {
  const adUnitId = String(value || '');
  return /^adunit-[A-Za-z0-9]{8,}$/.test(adUnitId) && !adUnitId.toLowerCase().includes('xxxxxxxx');
}

function writeConfig(adRewardAdUnitId) {
  const content = [
    '// Release packaging input generated by scripts/generate-release-ad-config.js.',
    '// The ad-unit ID is public client configuration; review and commit this change only when desired.',
    `module.exports = Object.freeze({ adRewardAdUnitId: ${JSON.stringify(adRewardAdUnitId)} });`,
    ''
  ].join('\n');
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, content, { mode: 0o600 });
}

function readConfiguredAdUnitId() {
  if (!fs.existsSync(output)) return null;
  delete require.cache[require.resolve(output)];
  return String(require(output).adRewardAdUnitId || '');
}

if (isDevConfig && isValidation) {
  fail('--dev and --validate cannot be used together.');
} else if (isDevConfig) {
  writeConfig('');
  process.stdout.write(`Reset release ad config to the unavailable default at ${output}.\n`);
} else {
  const adRewardAdUnitId = String(process.env.GAOKAO_RELEASE_AD_UNIT_ID || '').trim();
  if (!adRewardAdUnitId) {
    fail('GAOKAO_RELEASE_AD_UNIT_ID is required for release ad configuration.');
  } else if (!isUsableRewardedVideoAdUnit(adRewardAdUnitId)) {
    fail('GAOKAO_RELEASE_AD_UNIT_ID must be a valid WeChat rewarded-video ad unit (adunit-...) and not a placeholder.');
  } else if (isValidation) {
    const configuredAdUnitId = readConfiguredAdUnitId();
    if (configuredAdUnitId !== adRewardAdUnitId) {
      fail(`Generated release ad config is missing or does not match ${output}. Run the generator first.`);
    } else {
      process.stdout.write(`Validated generated release ad config at ${output}.\n`);
    }
  } else {
    writeConfig(adRewardAdUnitId);
    process.stdout.write(`Generated release ad config at ${output}.\n`);
  }
}
